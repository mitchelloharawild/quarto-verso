// Glossary: author-written source glossary keyed by stable ids, and a
// generated, reviewable glossary per language keyed by the same ids.

import { Document, parse } from 'yaml';
import { textHash } from './hash.ts';
import { flowStyle } from './tfile.ts';
import type { GlossaryEntry, LangGlossaryEntry } from './types.ts';

export function parseSourceGlossary(data: any): GlossaryEntry[] {
  if (!data || typeof data !== 'object') return [];
  return Object.entries(data).flatMap(([key, v]: [string, any]) => {
    if (!v || typeof v !== 'object' || typeof v.term !== 'string') return [];
    return [{ key, term: v.term, variants: Array.isArray(v.variants) ? v.variants.map(String) : [], definition: v.definition, keep: !!v.keep }];
  });
}

export function entryHash(e: GlossaryEntry): string {
  return textHash([e.term, ...(e.variants ?? []), e.definition ?? '', e.keep ? 'keep' : ''].join('\u0001'));
}

export function targetHash(e: LangGlossaryEntry | undefined): string {
  return e ? textHash([e.term, ...(e.variants ?? [])].join('\u0001')) : '';
}

function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function contains(text: string, form: string): boolean {
  return new RegExp(`(?<![\\p{L}\\p{N}])${escapeRe(form)}(?![\\p{L}\\p{N}])`, 'iu').test(text);
}

/** Entries whose term or variants occur in the text. */
export function hits(entries: GlossaryEntry[], text: string): GlossaryEntry[] {
  return entries.filter((e) => [e.term, ...(e.variants ?? [])].some((f) => contains(text, f)));
}

/** Warn when a source term occurs but none of the target term's forms does. */
export function termWarnings(entries: GlossaryEntry[], lang: Record<string, LangGlossaryEntry>, source: string, text: string): string[] {
  const out: string[] = [];
  for (const e of hits(entries, source)) {
    const forms = e.keep ? [e.term, ...(e.variants ?? [])] : lang[e.key] ? [lang[e.key].term, ...(lang[e.key].variants ?? [])] : [];
    if (forms.length && !forms.some((f) => contains(text, f))) out.push(`"${e.term}" → expected "${forms[0]}"`);
  }
  return out;
}

export interface LangGlossary {
  entries: Record<string, LangGlossaryEntry>;
}

export function parseLangGlossary(text: string): Record<string, LangGlossaryEntry> {
  const data = parse(text) ?? {};
  const out: Record<string, LangGlossaryEntry> = {};
  for (const [k, v] of Object.entries<any>(data)) {
    if (v && typeof v === 'object' && typeof v.term === 'string') {
      out[k] = { ...v, 'source-hash': String(v['source-hash']), reviews: v.reviews ?? [] };
    }
  }
  return out;
}

export function stringifyLangGlossary(lang: string, g: Record<string, LangGlossaryEntry>): string {
  const doc = new Document(g, { aliasDuplicateObjects: false });
  doc.commentBefore = ` Glossary for ${lang}, generated by quarto-i18n from the source glossary.\n Review and edit through pull requests like any translation.`;
  flowStyle(doc, ['origin', 'reviews']);
  return doc.toString({ lineWidth: 0 });
}

/** Hash of each current target term, for glossary-driven staleness. */
export function termHashes(entries: GlossaryEntry[], lang: Record<string, LangGlossaryEntry>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const e of entries) {
    const l = lang[e.key];
    if (l && l['source-hash'] === entryHash(e)) out[e.key] = targetHash(l);
  }
  return out;
}

/** Plain text only: no Markdown, HTML, shortcodes or code. */
export function isPlainText(s: string): boolean {
  return !/[<>`{}[\]$\\*_|]/.test(s) && !/\n/.test(s);
}
