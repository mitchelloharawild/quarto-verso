// YAML translation files: the project file's translation
// (`_i18n/<lang>/_project.yml`, from `_quarto.yml`), which has no document to
// hold its text. Also the common form of a translation that the contribution
// checks compare. Documents are stored as translated copies (tdoc.ts).

import { Document, isMap, isPair, isScalar, isSeq, parse, visit } from 'yaml';
import type { TFile, TUnit } from './types.ts';

/** The keys a unit may have, in the order they are written. */
export const UNIT_KEYS = ['id', 'kind', 'section', 'cell', 'field', 'source-hash', 'source', 'text', 'origin', 'reviews', 'reverted'];

/** Keys of a unit this version does not know (left by an older or newer version). */
export const unknownKeys = (u: object): string[] => Object.keys(u).filter((k) => !UNIT_KEYS.includes(k));

/** A unit with only the keys this version knows. */
export function knownPart(u: TUnit): TUnit {
  const o: any = {};
  for (const k of UNIT_KEYS) if ((u as any)[k] !== undefined) o[k] = (u as any)[k];
  return o;
}

export function header(sourcePath: string): string {
  return (
    `Generated by quarto-i18n from ${sourcePath}. Change translations through\n` +

    `reviewer mode or a pull request; \`i18n translate\` rewrites this file.`
  );
}

export function parseTFile(text: string): TFile {
  const data = parse(text) as TFile;
  if (!data || typeof data !== 'object' || !Array.isArray(data.units)) throw new Error('not a translation file (missing units)');
  for (const u of data.units) {
    if (typeof u.id !== 'string' || typeof u['source-hash'] !== 'string') throw new Error(`unit without id or source-hash`);
    u['source-hash'] = String(u['source-hash']);
    u.reviews = (u.reviews ?? []).map((r) => ({ by: String(r.by), date: String(r.date) }));
  }
  return data;
}

// Unknown keys are dropped when a file is written, so leftovers from older
// versions (such as `spans` from the first code-cell parser) disappear on the
// next `i18n translate`. `i18n check` reports them until then.
export function stringifyTFile(t: TFile): string {
  const doc = new Document({ source: t.source, lang: t.lang, units: t.units.map(knownPart) }, { aliasDuplicateObjects: false });
  doc.commentBefore = ' ' + header(t.source).replace(/\n/g, '\n ');
  flowStyle(doc, ['origin', 'reviews']);
  return doc.toString({ lineWidth: 0, defaultKeyType: 'PLAIN', singleQuote: false });
}

/** Render small maps (origin, reviews entries) in flow style for compact diffs. */
export function flowStyle(doc: Document, keys: string[]): void {
  visit(doc, {
    Pair(_k, pair) {
      if (!isPair(pair) || !isScalar(pair.key) || !keys.includes(String(pair.key.value))) return;
      const v = pair.value;
      if (isMap(v)) v.flow = true;
      if (isSeq(v)) for (const it of v.items) if (isMap(it)) it.flow = true;
    },
  });
}
