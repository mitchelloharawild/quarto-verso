// Parallel storage: each language keeps a translated copy of
// every source document (`_i18n/<lang>/<file>`) next to a tracking file
// (`_i18n/<lang>/<file>.yml`) that identifies its units and holds hashes and
// reviews, but no text.
//
// The rest of the tool works on the in-memory TFile, so this module only
// converts in both directions:
//
//   readParallel:  translated document + tracking file → TFile
//   writeParallel: current source + TFile             → translated document + tracking file
//
// Matching is positional: the n-th unit of the translated document is the n-th
// unit of the tracking file, which `writeParallel` guarantees and `readParallel`
// verifies (kind, cell, option or field, section). The tracking file is then
// aligned with the current source by the usual sync (sync.ts), so source edits
// never need guesswork. Everything outside units (cell options, attributes,
// fences, raw blocks) is taken from the source when rendering; the translated
// document only carries text.

import { Document, parse } from 'yaml';
import { codeHash, textHash } from './hash.ts';
import { applyEdits, setFrontMatter } from './materialise.ts';
import { blankUnit, syncUnits } from './sync.ts';
import { flowStyle, knownPart } from './tfile.ts';
import { extractUnits } from './units.ts';
import { normaliseBlockText, normaliseCode } from './validate.ts';
import type { MarkdownAdapter, SourceUnit, TFile, TUnit, UnitKind } from './types.ts';

export type TrackUnit = Omit<TUnit, 'text'> & { 'text-hash'?: string };

export interface TrackFile {
  source: string;
  lang: string;
  units: TrackUnit[];
}

export const TRACK_KEYS = ['id', 'kind', 'section', 'cell', 'field', 'source-hash', 'text-hash', 'terms', 'origin', 'reviews'];

export function normaliseText(kind: UnitKind, s: string): string {
  return kind === 'code' ? normaliseCode(s) : normaliseBlockText(s);
}

/** Hash of a translation, as recorded in `text-hash`. */
export function translationHash(kind: UnitKind, s: string): string {
  return kind === 'code' ? codeHash(normaliseCode(s)) : textHash(normaliseBlockText(s));
}

// ---- tracking file IO ---------------------------------------------------------

export function trackHeader(sourcePath: string, docPath: string): string {
  return (
    `Generated by quarto-i18n: tracks the units of ${docPath} (translated from\n` +
    `${sourcePath}): ids, hashes and reviews. Edit the translation in the .qmd;\n` +
    `\`i18n sync\` records the change here.`
  );
}

export function parseTrack(text: string): TrackFile {
  const data = parse(text) as TrackFile;
  if (!data || typeof data !== 'object' || !Array.isArray(data.units)) throw new Error('not a tracking file (missing units)');
  for (const u of data.units) {
    if (typeof u.id !== 'string' || typeof u['source-hash'] !== 'string') throw new Error('unit without id or source-hash');
    delete (u as any).source; // older tracking files kept a source snapshot
    if ('text' in u) throw new Error(`${u.id}: tracking files hold no text (the translation is in the .qmd)`);
    u['source-hash'] = String(u['source-hash']);
    if (u['text-hash'] !== undefined) u['text-hash'] = String(u['text-hash']);
    u.reviews = (u.reviews ?? []).map((r) => ({ by: String(r.by), date: String(r.date) }));
  }
  return data;
}

export function stringifyTrack(t: TrackFile, docPath: string): string {
  const units = t.units.map((u) => {
    const o: any = {};
    for (const k of TRACK_KEYS) if ((u as any)[k] !== undefined) o[k] = (u as any)[k];
    return o;
  });
  const doc = new Document({ source: t.source, lang: t.lang, units }, { aliasDuplicateObjects: false });
  doc.commentBefore = ' ' + trackHeader(t.source, docPath).replace(/\n/g, '\n ');
  flowStyle(doc, ['origin', 'reviews', 'terms']);
  return doc.toString({ lineWidth: 0, defaultKeyType: 'PLAIN', singleQuote: false });
}

// ---- read -----------------------------------------------------------------------

export interface ParallelIssue {
  /** `structure`: the document no longer matches the tracking file, so no unit can be used. */
  kind: 'structure' | 'untracked' | 'document';
  id?: string;
  line?: number;
  message: string;
}

export interface ParallelRead {
  /**
   * The translation file as stored: text from the document, everything else from
   * the tracking file. Units in `untracked` keep their recorded reviews here (the
   * contribution checks compare them); callers that display or count reviews must
   * use `withPolicy`.
   */
  tfile: TFile;
  /** Units whose text differs from the recorded `text-hash` (edited without `i18n sync`). */
  untracked: Set<string>;
  /** The document's own text of each unit, as written (for keeping line breaks on rewrite). */
  raw: Map<string, string>;
  /** Document units with positions, in order (only when the structure matches). */
  docUnits?: SourceUnit[];
  issues: ParallelIssue[];
}

const sig = (u: { kind: string; cell?: string; field?: string; section?: string }) =>
  [u.kind, u.cell ?? '', u.field ?? '', u.section ?? ''].join('|');

export async function readParallel(doc: string, track: TrackFile, md: MarkdownAdapter): Promise<ParallelRead> {
  const issues: ParallelIssue[] = [];
  const untracked = new Set<string>();
  const raw = new Map<string, string>();
  const ex = await extractUnits(doc, md);
  for (const i of ex.issues) if (i.level === 'error') issues.push({ kind: 'document', line: i.line, message: i.message });
  const base = (u: TrackUnit): TUnit => {
    const { 'text-hash': _h, ...rest } = u;
    return rest as TUnit;
  };

  const d = ex.units;
  const t = track.units;
  let mismatch = -1;
  for (let i = 0; i < Math.max(d.length, t.length); i++) {
    if (!d[i] || !t[i] || sig(d[i]) !== sig(t[i])) {
      mismatch = i;
      break;
    }
  }
  // Same kinds in the same order can still hide moved text (a merge and a split
  // in one section): a block holding the recorded text of another unit.
  if (mismatch === -1) {
    const recorded = new Map<string, number>();
    t.forEach((tu, j) => tu['text-hash'] && !recorded.has(tu['text-hash']) && recorded.set(tu['text-hash'], j));
    for (let i = 0; i < t.length; i++) {
      const h = translationHash(t[i].kind, d[i].source);
      const j = recorded.get(h);
      if (h !== t[i]['text-hash'] && j !== undefined && j !== i && t[j]['text-hash'] !== translationHash(t[j].kind, d[j].source)) {
        mismatch = Math.min(i, j);
        issues.push({ kind: 'structure', message: `the translation's structure differs from its tracking file: block ${i + 1} holds the recorded translation of unit ${j + 1} (${t[j].id}), so blocks were moved, merged or split. ${FIX}` });
        break;
      }
    }
  } else {
    issues.push({ kind: 'structure', message: describeMismatch(d, t, mismatch) });
  }

  // `verified`: the text is exactly the recorded translation (or the untouched source).
  const fill = (tu: TrackUnit, du: SourceUnit, verifiedOnly: boolean): TUnit => {
    const u = base(tu);
    const text = normaliseText(tu.kind, du.source);
    if (tu['text-hash']) {
      if (translationHash(tu.kind, text) === tu['text-hash']) {
        u.text = text;
        raw.set(tu.id, du.source);
      } else if (!verifiedOnly) {
        u.text = text;
        raw.set(tu.id, du.source);
        untracked.add(tu.id);
        issues.push({ kind: 'untracked', id: tu.id, message: 'translation edited without updating the tracking file (run `i18n sync`)' });
      }
    } else if (du.hash !== tu['source-hash']) {
      // Not translated before, and the document no longer holds the source text:
      // someone translated it by hand.
      if (!verifiedOnly) {
        u.text = text;
        raw.set(tu.id, du.source);
        untracked.add(tu.id);
        issues.push({ kind: 'untracked', id: tu.id, message: 'new translation not recorded in the tracking file (run `i18n sync`)' });
      }
    }
    return u;
  };

  if (mismatch !== -1) {
    // Units before the first difference and after the last one may still line
    // up; only those holding exactly their recorded translation are used, the
    // rest show the source until the structure is fixed.
    let suffix = 0;
    while (suffix < d.length - mismatch && suffix < t.length - mismatch && sig(d[d.length - 1 - suffix]) === sig(t[t.length - 1 - suffix])) suffix++;
    const units = t.map((tu, i) => (i < mismatch ? fill(tu, d[i], true) : i >= t.length - suffix ? fill(tu, d[d.length - t.length + i], true) : base(tu)));
    return { tfile: { source: track.source, lang: track.lang, units }, untracked, raw, issues };
  }

  const units = t.map((tu, i) => fill(tu, d[i], false));
  return { tfile: { source: track.source, lang: track.lang, units }, untracked, raw, docUnits: d, issues };
}

const FIX = 'Keep one block per source block (same headings, paragraphs, list items, cells), or rewrite it from the source with `i18n sync --reset` (units that no longer line up are lost).';

function describeMismatch(d: SourceUnit[], t: TrackUnit[], i: number): string {
  const name = (u?: { kind: string; cell?: string; field?: string; section?: string }) =>
    u ? `${u.kind}${u.cell ? ` (cell ${u.cell}${u.field ? ` ${u.field}` : ''})` : u.field ? ` (${u.field})` : ''}${u.section ? ` in #${u.section}` : ''}` : 'nothing';
  const where = t[i]?.section ?? d[i]?.section ?? t[i - 1]?.section;
  const count = (xs: { section?: string }[]) => xs.filter((x) => x.section === where).length;
  const counts = where ? `; #${where} has ${count(d)} units in the translation and ${count(t)} in the tracking file` : '';
  return `the translation's structure differs from its tracking file at unit ${i + 1}: found ${name(d[i])}, expected ${name(t[i])}${counts}. ${FIX}`;
}

/**
 * Display policy: an edit not recorded in the tracking file is a translation by
 * an unknown person, so earlier reviews (of a different text) do not count.
 */
export function withPolicy(r: ParallelRead): TFile {
  return {
    ...r.tfile,
    units: r.tfile.units.map((u) => (r.untracked.has(u.id) ? { ...u, origin: { by: 'unknown', date: '' }, reviews: [] } : u)),
  };
}

// ---- write ----------------------------------------------------------------------

export interface ParallelWrite {
  doc: string;
  track: TrackFile;
}

/**
 * Write the translated document from the current source: every unit's range is
 * replaced by its translation (current or stale), or keeps the source text when
 * there is none. Structure, options and attributes always come from the source,
 * so the document is block-for-block parallel to the tracking file written with it.
 */
export function writeParallel(file: string, sourceText: string, srcUnits: SourceUnit[], tfile: TFile, raw?: Map<string, string>): ParallelWrite {
  const synced = syncUnits(file, srcUnits, tfile);
  const edits: { start: number; end: number; text: string }[] = [];
  const meta: { path: (string | number)[]; value: string }[] = [];
  const track: TrackUnit[] = [];
  for (const u of synced) {
    const s = u.src;
    const st = u.stored ?? blankUnit(u);
    const text = typeof st.text === 'string' && st.text.length ? normaliseText(s.kind, st.text) : undefined;
    const { text: _t, ...rest } = knownPart(st);
    const tu: TrackUnit = rest;
    delete tu.source; // no text in tracking files
    // An untranslated unit holds the current source text in the document, so its
    // source-hash tells it from a hand translation.
    if (text === undefined) tu['source-hash'] = s.hash;
    if (text !== undefined) tu['text-hash'] = translationHash(s.kind, text);
    track.push(orderTrack(tu));
    if (text === undefined) continue; // the source text stays in place
    if (s.kind === 'block') {
      const r = raw?.get(u.id);
      let value = text;
      if (r !== undefined && normaliseBlockText(r) === text && r.includes('\n')) {
        // Keep the translator's line breaks, re-indented for the source's position.
        const col = s.range!.start - (sourceText.lastIndexOf('\n', s.range!.start - 1) + 1);
        value = r.replace(/\n[ \t]*/g, '\n' + ' '.repeat(col));
      }
      edits.push({ start: s.range!.start, end: s.range!.end, text: value });
    } else if (s.kind === 'caption') {
      const line = sourceText.slice(s.range!.start, s.range!.end);
      const prefix = /^#\|\s*/.exec(line)![0];
      edits.push({ start: s.range!.start, end: s.range!.end, text: `${prefix}${s.field}: ${JSON.stringify(text)}` });
    } else if (s.kind === 'code') {
      edits.push({ start: s.range!.start, end: s.range!.end, text });
    } else if (s.kind === 'meta') {
      meta.push({ path: s.field!.split('.').map((k) => (/^\d+$/.test(k) ? Number(k) : k)), value: text });
    }
  }
  const doc = setFrontMatter(applyEdits(sourceText, edits), meta);
  return { doc, track: { source: tfile.source, lang: tfile.lang, units: track } };
}

function orderTrack(u: TrackUnit): TrackUnit {
  const o: any = {};
  for (const k of TRACK_KEYS) if ((u as any)[k] !== undefined) o[k] = (u as any)[k];
  return o;
}

/**
 * Text outside the units, for comparing two versions of a translated document:
 * unit text is replaced by a marker, so only changes to structure, options,
 * attributes, raw blocks and front matter (other than translated fields) remain.
 */
export function outsideUnits(doc: string, docUnits: SourceUnit[]): string {
  const edits = docUnits.filter((u) => u.range).map((u, k) => ({ start: u.range!.start, end: u.range!.end, text: `\u0000${k}\u0000` }));
  let out = applyEdits(doc, edits);
  const metaFields = docUnits.filter((u) => u.kind === 'meta').map((u) => u.field!.split('.'));
  if (metaFields.length) {
    const m = /^---[ \t]*\r?\n([\s\S]*?)\r?\n(?:---|\.\.\.)[ \t]*(?:\r?\n|$)/.exec(out);
    if (m) {
      const data = parse(m[1]) ?? {};
      for (const f of metaFields) {
        let o = data;
        for (const k of f.slice(0, -1)) o = o?.[k];
        if (o && typeof o === 'object') o[f[f.length - 1]] = '\u0000';
      }
      out = JSON.stringify(data) + '\n' + out.slice(m[0].length);
    }
  }
  return out;
}
